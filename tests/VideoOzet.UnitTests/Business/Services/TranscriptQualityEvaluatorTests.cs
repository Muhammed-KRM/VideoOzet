namespace VideoOzet.UnitTests.Business.Services;

public class TranscriptQualityEvaluatorTests
{
    private readonly TranscriptQualityEvaluator _evaluator = new();

    private static string BuildCleanTurkishText(int targetWords)
    {
        var sentences = new[]
        {
            "Merhaba arkadaşlar bugün yazılım mimarisi ve temiz kod prensipleri hakkında detaylı bir inceleme yapacağız",
            "Dağıtık sistemlerde mesaj kuyrukları servisler arasındaki bağımlılığı azaltarak ölçeklenebilirliği önemli ölçüde artırır",
            "Veritabanı şemalarının geriye dönük uyumlu güncellenmesi üretim ortamında kesintisiz çalışma için kritik öneme sahiptir",
            "Birim testleri iş kurallarının beklenen sınır koşullarında doğru çalıştığını erken aşamada güvence altına alır",
            "Önbellekleme katmanı sık erişilen yapılandırma verilerini hızlı biçimde sunarak gecikme süresini düşürür",
            "Kullanıcı arayüzünde net durum bildirimleri göstermek uzun süren işlemlerde deneyimi doğrudan iyileştirir",
            "Hata yönetimi mekanizmaları beklenmeyen ağ kesintilerinde bile sistemin kararlı kalmasını sağlar",
            "Otomatik kalite değerlendirme adımı düşük kaliteli altyazıları eleyerek özetleme doğruluğunu yükseltir"
        };

        var words = new List<string>();
        int idx = 0;
        while (words.Count < targetWords)
        {
            var tokens = sentences[idx % sentences.Length].Split(' ', StringSplitOptions.RemoveEmptyEntries);
            foreach (var token in tokens)
            {
                if (words.Count >= targetWords) break;
                // Add slight suffix variation across cycles so 4-grams stay unique
                var cycle = idx / sentences.Length;
                words.Add(cycle == 0 ? token : $"{token}{cycle}");
            }
            idx++;
        }

        return string.Join(' ', words);
    }

    private static string BuildCleanEnglishText(int targetWords)
    {
        var sentences = new[]
        {
            "Hello everyone today we will explore software architecture and clean design principles across distributed systems",
            "Message queues decouple background workers from web controllers and improve overall system resilience under heavy load",
            "Database schema migrations should remain backward compatible when upgrading standalone desktop installations safely",
            "Unit tests verify that deterministic business rules behave properly across boundary inputs and failure paths",
            "Caching layers reduce latency by serving frequently accessed configuration settings directly from memory",
            "Clear progress notifications in the user interface help operators monitor long running media pipelines",
            "Automated quality gates prevent noisy captions from degrading downstream summarization accuracy",
            "Structured error handling ensures transient network failures never corrupt persisted application state"
        };

        var words = new List<string>();
        int idx = 0;
        while (words.Count < targetWords)
        {
            var tokens = sentences[idx % sentences.Length].Split(' ', StringSplitOptions.RemoveEmptyEntries);
            foreach (var token in tokens)
            {
                if (words.Count >= targetWords) break;
                var cycle = idx / sentences.Length;
                words.Add(cycle == 0 ? token : $"{token}{cycle}");
            }
            idx++;
        }

        return string.Join(' ', words);
    }

    [Fact]
    public void Evaluate_CleanManualTurkishTranscript_ReceivesManualBonusAndPasses()
    {
        var text = BuildCleanTurkishText(80);

        var manualReport = _evaluator.Evaluate(text, durationSeconds: 60, expectedLang: "tr", isManualCaption: true);
        var autoReport = _evaluator.Evaluate(text, durationSeconds: 60, expectedLang: "tr", isManualCaption: false);

        manualReport.GectiMi.Should().BeTrue();
        manualReport.Skor.Should().Be(100);
        manualReport.Skor.Should().Be(autoReport.Skor + 15);
        manualReport.KelimeDakika.Should().BeApproximately(80.0, 0.5);
        manualReport.TekrarOrani.Should().BeLessThan(0.20);
        manualReport.OzetNeden.Should().Contain("Manuel altyazı");
    }

    [Fact]
    public void Evaluate_CleanAutoGeneratedTranscript_WithoutManualBonus_StillPassesAboveThreshold()
    {
        var text = BuildCleanTurkishText(80);

        var report = _evaluator.Evaluate(text, durationSeconds: 60, expectedLang: "tr", isManualCaption: false);

        report.GectiMi.Should().BeTrue();
        report.Skor.Should().Be(85);
        report.Skor.Should().BeGreaterThanOrEqualTo(70);
        report.OzetNeden.Should().Contain("Otomatik altyazı");
    }

    [Fact]
    public void Evaluate_VeryLowWpmBelow25_HardRejectsTranscript()
    {
        // 55 words (>= 50 min words) in 180 seconds = 18.3 WPM (< 25)
        var text = BuildCleanTurkishText(55);

        var report = _evaluator.Evaluate(text, durationSeconds: 180, expectedLang: "tr", isManualCaption: true);

        report.GectiMi.Should().BeFalse();
        report.Skor.Should().BeLessThanOrEqualTo(49);
        report.KelimeDakika.Should().BeLessThan(25);
        report.OzetNeden.Should().Contain("WPM < 25");
    }

    [Fact]
    public void Evaluate_ModeratelyLowWpmBetween25And39_Applies20PointPenalty()
    {
        // 60 words in 120 seconds = 30.0 WPM (25 <= WPM < 40)
        var text = BuildCleanTurkishText(60);

        var manualReport = _evaluator.Evaluate(text, durationSeconds: 120, expectedLang: "tr", isManualCaption: true);
        var autoReport = _evaluator.Evaluate(text, durationSeconds: 120, expectedLang: "tr", isManualCaption: false);

        manualReport.KelimeDakika.Should().BeApproximately(30.0, 0.5);
        manualReport.Skor.Should().Be(80); // 100 - 20
        manualReport.GectiMi.Should().BeTrue();

        autoReport.Skor.Should().Be(65); // 85 - 20 (< 70)
        autoReport.GectiMi.Should().BeFalse();
    }

    [Fact]
    public void Evaluate_HighWpmAbove260_Applies25PointPenalty()
    {
        // 60 words in 10 seconds = 360.0 WPM (> 260)
        var text = BuildCleanTurkishText(60);

        var manualReport = _evaluator.Evaluate(text, durationSeconds: 10, expectedLang: "tr", isManualCaption: true);
        var autoReport = _evaluator.Evaluate(text, durationSeconds: 10, expectedLang: "tr", isManualCaption: false);

        autoReport.KelimeDakika.Should().BeGreaterThan(260);
        autoReport.Skor.Should().Be(60); // 85 - 25
        autoReport.GectiMi.Should().BeFalse();
        autoReport.OzetNeden.Should().Contain("WPM > 260");

        manualReport.Skor.Should().Be(75); // 100 - 25
    }

    [Fact]
    public void Evaluate_HighFourGramRepetitionAbove30Percent_HardRejectsTranscript()
    {
        // Repeat a 6-word Turkish phrase 12 times = 72 words with very high 4-gram repetition
        var phrase = "bu ders boyunca sürekli tekrar ediyoruz";
        var text = string.Join(' ', Enumerable.Repeat(phrase, 12));

        var report = _evaluator.Evaluate(text, durationSeconds: 60, expectedLang: "tr", isManualCaption: true);

        report.GectiMi.Should().BeFalse();
        report.Skor.Should().BeLessThanOrEqualTo(49);
        report.TekrarOrani.Should().BeGreaterThan(0.30);
        report.OzetNeden.Should().Contain("4-gram tekrar oranı");
    }

    [Fact]
    public void Evaluate_HeavyNonSpeechTagsAbove50Percent_HardRejectsTranscript()
    {
        // 55 clean words + 60 non-speech tags -> 60 / 115 ≈ 52.2% >= 50%
        var speech = BuildCleanTurkishText(55);
        var tags = string.Join(' ', Enumerable.Repeat("[Müzik] [Alkış] [Music]", 20));
        var text = $"{tags} {speech}";

        var report = _evaluator.Evaluate(text, durationSeconds: 60, expectedLang: "tr", isManualCaption: true);

        report.GectiMi.Should().BeFalse();
        report.Skor.Should().BeLessThanOrEqualTo(49);
        report.OzetNeden.Should().Contain("konuşma dışı etiket oranı");
    }

    [Fact]
    public void Evaluate_ModerateNonSpeechTagsBetween25And49Percent_Applies25PointPenalty()
    {
        // 60 words + 24 tags -> 24 / 84 ≈ 28.6% (>= 25%, < 50%)
        var speech = BuildCleanTurkishText(60);
        var tags = string.Join(' ', Enumerable.Repeat("[Müzik] [Alkış]", 12));
        var text = $"{tags} {speech}";

        var autoReport = _evaluator.Evaluate(text, durationSeconds: 60, expectedLang: "tr", isManualCaption: false);
        var manualReport = _evaluator.Evaluate(text, durationSeconds: 60, expectedLang: "tr", isManualCaption: true);

        autoReport.Skor.Should().Be(60); // 85 - 25
        autoReport.GectiMi.Should().BeFalse();
        manualReport.Skor.Should().Be(75); // 100 - 25
        manualReport.OzetNeden.Should().Contain("ses/müzik etiketi oranı");
    }

    [Fact]
    public void Evaluate_MinimumWordCount_RejectsInsufficientWordsForNormalAndShortVideos()
    {
        // Normal duration (>= 60s): 40 words < 50 minimum
        var normalShortText = BuildCleanTurkishText(40);
        var normalReport = _evaluator.Evaluate(normalShortText, durationSeconds: 60, expectedLang: "tr", isManualCaption: true);

        normalReport.GectiMi.Should().BeFalse();
        normalReport.Skor.Should().BeLessThanOrEqualTo(49);
        normalReport.OzetNeden.Should().Contain("yetersiz kelime sayısı");

        // Short video (< 60s): 12 words < 15 minimum
        var veryShortText = BuildCleanTurkishText(12);
        var shortReport = _evaluator.Evaluate(veryShortText, durationSeconds: 30, expectedLang: "tr", isManualCaption: true);

        shortReport.GectiMi.Should().BeFalse();
        shortReport.Skor.Should().BeLessThanOrEqualTo(49);
        shortReport.OzetNeden.Should().Contain("yetersiz kelime sayısı");

        // Short video (< 60s) with 25 words in 20s (75 WPM, >= 15 words) should pass
        var validShortText = BuildCleanTurkishText(25);
        var validShortReport = _evaluator.Evaluate(validShortText, durationSeconds: 20, expectedLang: "tr", isManualCaption: true);
        validShortReport.GectiMi.Should().BeTrue();
    }

    [Fact]
    public void Evaluate_LanguageMismatch_HardRejectsMismatchedLanguage()
    {
        var englishText = BuildCleanEnglishText(70);
        var turkishText = BuildCleanTurkishText(70);

        var trExpectedOnEn = _evaluator.Evaluate(englishText, durationSeconds: 60, expectedLang: "tr", isManualCaption: true);
        trExpectedOnEn.GectiMi.Should().BeFalse();
        trExpectedOnEn.Skor.Should().BeLessThanOrEqualTo(49);
        trExpectedOnEn.OzetNeden.Should().Contain("beklenen dil (tr)");

        var enExpectedOnTr = _evaluator.Evaluate(turkishText, durationSeconds: 60, expectedLang: "en", isManualCaption: true);
        enExpectedOnTr.GectiMi.Should().BeFalse();
        enExpectedOnTr.Skor.Should().BeLessThanOrEqualTo(49);
        enExpectedOnTr.OzetNeden.Should().Contain("beklenen dil (en)");
    }

